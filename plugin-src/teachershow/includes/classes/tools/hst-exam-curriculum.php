    private static ?array $catalog = null;

    public static function catalog(): array
    {
        if (self::$catalog !== null) {
            return self::$catalog;
        }

        $subjects = self::subjects();
        $paths = self::paths();
        $catalog = [];

        foreach ($paths as $grade => $majors) {
            $catalog[$grade] = [
                'label'  => self::GRADE_LABELS[$grade],
                'majors' => [],
            ];
            foreach ($majors as $major => $subject_keys) {
                $major_subjects = [];
                foreach ($subject_keys as $subject_key) {
                    if (isset($subjects[$subject_key])) {
                        $major_subjects[$subject_key] = $subjects[$subject_key];
                    }
                }
                $catalog[$grade]['majors'][$major] = [
                    'label'    => self::MAJOR_LABELS[$major],
                    'subjects' => $major_subjects,
                ];
            }
        }

        self::$catalog = $catalog;
        return self::$catalog;
    }

    public static function public_catalog(): array
    {
        return [
            'source' => [
                'title'       => self::SOURCE_LABEL,
                'publisher'   => 'وزارت آموزش و پرورش، سازمان پژوهش و برنامه‌ریزی آموزشی',
                'school_year' => '۱۴۰۵–۱۴۰۴',
            ],
            'grades' => self::catalog(),
        ];
    }

    public static function validate_selection(string $grade, string $major, string $subject, array $topics): array
    {
        $catalog = self::catalog();
        if (!isset($catalog[$grade]['majors'][$major]['subjects'][$subject])) {
            return [];
        }

        $entry = $catalog[$grade]['majors'][$major]['subjects'][$subject];
        $valid = [];
        foreach (self::subject_units($entry) as $unit) {
            foreach ((array) ($unit['topics'] ?? []) as $topic) {
                $valid[(string) ($topic['id'] ?? '')] = true;
            }
        }

        return array_values(array_filter(array_unique(array_map('sanitize_key', $topics)), static function ($topic) use ($valid) {
            return isset($valid[$topic]);
        }));
    }

    public static function subject_units(array $entry): array
    {
        $units = [];
        foreach ((array) ($entry['chapters'] ?? []) as $chapter) {
            $chapter['kind'] = 'chapter';
            $units[] = $chapter;
        }
        foreach ((array) ($entry['sections'] ?? []) as $section) {
            $section['kind'] = 'section';
            $units[] = $section;
        }
        return $units;
    }

    public static function unit_topic_ids(array $entry, string $unit_id): array
    {
        foreach (self::subject_units($entry) as $unit) {
            if ((string) ($unit['id'] ?? '') === $unit_id) {
                return array_values(array_filter(array_map('strval', array_column((array) ($unit['topics'] ?? []), 'id'))));
            }
        }
        return [];
    }

    private static function subject(string $title, string $grade, string $pages, array $chapters, string $edition = '', array $sections = []): array
    {
        return [
            'title'    => $title,
            'grade'    => $grade,
            'chapters' => $chapters,
            'sections' => $sections,
            'source'   => [
                'document' => self::SOURCE_LABEL,
                'pages'    => $pages,
                'edition'  => $edition,
            ],
        ];
    }

    private static function chapters(array $titles, string $prefix = 'فصل'): array
    {
        $result = [];
        foreach (array_values($titles) as $index => $value) {
            $number = $index + 1;
            $topics = [];
            $title = '';
            if (is_array($value)) {
                $title = (string) ($value['title'] ?? '');
                foreach ((array) ($value['topics'] ?? []) as $topic_index => $topic_title) {
                    $topics[] = [
                        'id'    => 'c' . $number . '-t' . ($topic_index + 1),
                        'title' => (string) $topic_title,
                    ];
                }
            } else {
                $title = (string) $value;
            }

            if (!$topics) {
                $scope = $title !== '' ? $title : $prefix . ' ' . self::ordinal($number);
                $default_topics = [
                    'مفاهیم، اصطلاحات و تعریف‌های کلیدی «' . $scope . '»',
                    'روابط، قواعد و نکات اصلی «' . $scope . '»',
                    'تحلیل مثال‌ها، شواهد، نمودارها و فعالیت‌های «' . $scope . '»',
                    'کاربرد آموخته‌ها و پاسخ‌گویی به مسئله‌های «' . $scope . '»',
                ];
                foreach ($default_topics as $topic_index => $topic_title) {
                    $topics[] = [
                        'id'    => 'c' . $number . '-t' . ($topic_index + 1),
                        'title' => $topic_title,
                    ];
                }
            }

            $result[] = [
                'id'     => 'c' . $number,
                'title'  => $prefix . ' ' . self::ordinal($number) . ($title !== '' ? ': ' . $title : ''),
                'topics' => $topics,
            ];
        }
        return $result;
    }

    private static function numbered(int $count, string $prefix = 'درس'): array
    {
        return self::chapters(array_fill(0, $count, ''), $prefix);
    }

